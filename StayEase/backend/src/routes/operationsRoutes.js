const router = require('express').Router();
const auth = require('../middleware/authMiddleware');
const admin = require('../middleware/adminMiddleware');
const c = require('../controllers/operationsController');
router.use(auth, admin);
router.get('/payments', c.listPayments);
router.post('/payments', c.createPayment);
router.get('/maintenance', c.listMaintenance);
router.post('/maintenance', c.createMaintenance);
router.patch('/maintenance/:id', c.updateMaintenance);
module.exports = router;
