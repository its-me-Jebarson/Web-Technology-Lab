const router = require('express').Router();
const c = require('../controllers/roomController');
const auth = require('../middleware/authMiddleware');
const admin = require('../middleware/adminMiddleware');
router.get('/', c.listRooms);
router.get('/admin/all', auth, admin, c.adminListRooms);
router.get('/:id', c.getRoom);
router.post('/', auth, admin, c.createRoom);
router.put('/:id', auth, admin, c.updateRoom);
router.delete('/:id', auth, admin, c.deleteRoom);
module.exports = router;
